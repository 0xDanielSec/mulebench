            f"| {_model_of(report)} | {part(m, 'memory', 'memory_injected')} "
            f"| {part(m, 'memory', 'memory_followed')} "
            f"| {kn(sum(bool(x.get('handoff_tainted')) for x in dm), len(d))} "
            f"| {kn(sum(bool(x.get('crossed_boundary')) for x in dm), len(d))} |"
