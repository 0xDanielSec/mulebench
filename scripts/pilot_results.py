"""Render the Results section of a local pilot write-up from its committed reports.

Usage: uv run python scripts/pilot_results.py [--check]

Reads the JSON reports in docs/experiments/data/ listed in PILOTS and rewrites
the block between the results markers of each pilot document. With --check,
nothing is written and the exit code is 1 if a document is out of date (the
same check runs in tests/test_pilot_results.py).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from mulebench.harness.stats import wilson

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "experiments" / "data"
START = "<!-- results:start (generated by scripts/pilot_results.py; do not edit) -->"
END = "<!-- results:end -->"

# document -> reports, in the order they are shown
PILOTS: dict[str, list[str]] = {
    "docs/experiments/local-pilot-01.md": [
        "pilot-01-qwen3-14b-8k.json",
        "pilot-01-llama31-8b-8k.json",
    ],
}

PROMPT_SHORT = {"baseline": "baseline", "data_not_instructions": "data_not_instr."}


def rate(r: dict[str, Any] | None) -> str:
    if r is None or r["n"] == 0:
        return "n/a (n=0)"
    return f"{r['k']}/{r['n']} ({r['rate']:.0%}, {r['low']:.0%}-{r['high']:.0%})"


def short_id(scenario_id: str) -> str:
    return scenario_id.rsplit("-", 1)[-1]


def counts(d: dict[str, int]) -> str:
    return ", ".join(f"{k} {v}" for k, v in sorted(d.items())) or "-"


def add(into: dict[str, int], d: dict[str, int]) -> None:
    for k, v in d.items():
        into[k] = into.get(k, 0) + v


def cells_by_row(report: dict[str, Any]) -> dict[tuple[str, str], dict[str, Any]]:
    """Per (scenario, prompt): malformed, coerced, outflow and error kinds over both variants."""
    out: dict[tuple[str, str], dict[str, Any]] = {}
    for s in report["scenarios"]:
        for c in s["cells"]:
            row = out.setdefault(
                (s["scenario_id"], c["prompt_variant"]),
                {"malformed": {}, "coerced": 0, "outflow": 0, "errors": {}, "near": 0},
            )
            add(row["malformed"], c["malformed_tool_calls"])
            row["coerced"] += c["coerced_calls"]
            row["near"] += c["context_near_limit"]
            if c["variant"] == "attack":
                row["outflow"] += c["unauthorized_outflow_cents"]
            for t in c["trials"]:
                if t["errored"]:
                    add(row["errors"], {f"{c['variant']} {t['error'] or 'unknown'}": 1})
    return out


def render_model(report: dict[str, Any], file_name: str) -> list[str]:
    llm, totals = report["llm"], report["summary"]["totals"]
    rows = sorted(
        report["summary"]["rows"], key=lambda r: (short_id(r["scenario_id"]), r["prompt_variant"])
    )
    extra = cells_by_row(report)
    lines = [
        f"### {llm['model']}",
        "",
        f"Source: `docs/experiments/data/{file_name}` (run status `{report['run_status']}`, "
        f"tool schema `{llm['tool_schema_sha256'][:12]}`). "
        f"Attack trials {totals['attack_trials']}, benign trials {totals['benign_trials']}, "
        f"errored {totals['errored']}, not_exposed {totals['not_exposed']}, "
        f"not-meaningful rows {totals['not_meaningful_rows']} of {len(rows)}.",
        "",
        "**Attack variant** (rates over exposed, non-errored attack trials).",
        "",
        "| Scen. | Prompt | Attack success | Refusal | Errored | Not exposed | Outflow (cents) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        a, x = r["attack"], extra[(r["scenario_id"], r["prompt_variant"])]
        lines.append(
            f"| {short_id(r['scenario_id'])} | {PROMPT_SHORT[r['prompt_variant']]} "
            f"| {rate(a['attack_success'])} | {rate(a['refusal'])} "
            f"| {a['errored']}/{a['trials']} | {a['not_exposed']}/{a['trials']} | {x['outflow']} |"
        )
    lines += [
        "",
        "**Benign control and validity** (validity over all trials of the row; malformed "
        "and coerced counts over both variants).",
        "",
        "| Scen. | Prompt | Benign utility | Errored (benign) | Tool-call validity "
        "| Malformed | Coerced calls | Meaningful |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        b, x = r["benign"], extra[(r["scenario_id"], r["prompt_variant"])]
        meaningful = (
            "yes" if r["resistance_meaningful"] else "no: " + ", ".join(r["not_meaningful_reasons"])
        )
        lines.append(
            f"| {short_id(r['scenario_id'])} | {PROMPT_SHORT[r['prompt_variant']]} "
            f"| {rate(b['utility_exact'])} | {b['errored']}/{b['trials']} "
            f"| {rate(r['tool_call_validity'])} | {counts(x['malformed'])} "
            f"| {x['coerced']} | {meaningful} |"
        )
    errors: dict[str, int] = {}
    for x in extra.values():
        add(errors, x["errors"])
    near = sum(x["near"] for x in extra.values())
    lines += [
        "",
        f"Error kinds (trials): {counts(errors)}. Coerced arguments: "
        f"{counts(totals['coerced_args'])}. Model calls at >= 90% of num_ctx: {near}.",
        "",
        "**RQ2 / RQ3 side by side** (difference = data_not_instr. minus baseline, "
        "percentage points; no significance tests).",
        "",
        "| Scen. | Attack success: baseline | data_not_instr. | Diff. "
        "| Benign utility: baseline | data_not_instr. | Diff. |",
        "|---|---|---|---|---|---|---|",
    ]
    by_key = {(r["scenario_id"], r["prompt_variant"]): r for r in rows}
    pooled: dict[str, list[int]] = {}
    for sid in sorted({r["scenario_id"] for r in rows}, key=short_id):
        base, defd = by_key[(sid, "baseline")], by_key[(sid, "data_not_instructions")]
        cols = []
        for metric, part in (("attack_success", "attack"), ("utility_exact", "benign")):
            rb, rd = base[part][metric], defd[part][metric]
            diff = f"{(rd['rate'] - rb['rate']) * 100:+.0f}" if rb["n"] and rd["n"] else "n/a"
            cols += [rate(rb), rate(rd), diff]
            if metric == "attack_success":
                for name, rr in (("baseline", rb), ("data_not_instructions", rd)):
                    acc = pooled.setdefault(name, [0, 0])
                    acc[0] += rr["k"]
                    acc[1] += rr["n"]
        lines.append(f"| {short_id(sid)} | " + " | ".join(cols) + " |")
    lines += [
        "",
        "Pooled, descriptive (not an estimate; scenarios are not exchangeable, and trials "
        "with the same seed share their first model call, see Findings): attack success "
        + "; ".join(
            f"{PROMPT_SHORT[p]} {rate(wilson(k, n).model_dump())}" for p, (k, n) in pooled.items()
        )
        + ".",
        "",
    ]
    return lines


def render(doc: str) -> str:
    lines: list[str] = [
        START,
        "",
        "Format: k/n (rate, Wilson 95% interval). Scenario ids are shortened to their "
        "number (001 injection, 002 confused deputy, 003 payee name, 004 cross-customer "
        "read, 005 structuring, 006 foreign debit, 007 drain). Preset `vulnerable` only.",
        "",
    ]
    for name in PILOTS[doc]:
        report = json.loads((DATA / name).read_text(encoding="utf-8"))
        lines += render_model(report, name)
    lines.append(END)
    return "\n".join(lines)


def updated(doc: str) -> tuple[str, str]:
    text = (ROOT / doc).read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    return text, text[:start] + render(doc) + text[end:]


def main(argv: list[str]) -> int:
    stale = []
    for doc in PILOTS:
        old, new = updated(doc)
        if old != new:
            stale.append(doc)
            if "--check" not in argv:
                (ROOT / doc).write_text(new, encoding="utf-8", newline="\n")
    if "--check" in argv and stale:
        print("out of date: " + ", ".join(stale))
        return 1
    print("rewritten: " + (", ".join(stale) or "nothing"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
