def source_name(path: Path) -> Path:
    """The path as shown in Source lines: repo-relative when inside the repo."""
    try:
        return path.resolve().relative_to(ROOT)
    except ValueError:
        return path


def analyse(pilot: str, paths: list[Path]) -> list[str]:
    """The results block of pilot 04 or 05 from run reports (any order)."""
    reports = [(source_name(p), json.loads(p.read_text(encoding="utf-8"))) for p in paths]
    runs = [(p, r) for p, r in reports if r.get("kind") != "workload-run"]
    workloads = [(p, r) for p, r in reports if r.get("kind") == "workload-run"]
    if pilot == "04":
        if len(runs) != 1 or workloads:
            raise SystemExit("pilot 04 takes exactly one run report")
        return render_pilot_04(runs[0][1], runs[0][0].as_posix())
    if pilot == "05":
        if len(runs) > 1 or len(workloads) > 1 or not reports:
            raise SystemExit("pilot 05 takes at most one run report and one workload report")
        run = runs[0] if runs else None
        wk = workloads[0] if workloads else None
        return render_pilot_05(
            None if run is None else run[1],
            "" if run is None else run[0].as_posix(),
            None if wk is None else wk[1],
            "" if wk is None else wk[0].as_posix(),
        )
    if pilot == "06":
        if len(runs) > 1 or len(workloads) > 1 or not reports:
            raise SystemExit("pilot 06 takes at most one run report and one workload report")
        run = runs[0] if runs else None
        wk = workloads[0] if workloads else None
        return render_pilot_06(
            None if run is None else run[1],
            "" if run is None else run[0].as_posix(),
            None if wk is None else wk[1],
            "" if wk is None else wk[0].as_posix(),
            load(PILOT_05_RUN),
            load(PILOT_05_WORKLOAD),
        )
    if pilot == "07":
        if len(runs) != 1 or workloads:
            raise SystemExit("pilot 07 takes exactly one run report")
        return render_pilot_07(runs[0][1], runs[0][0].as_posix())
    if pilot == "08":
        if not 1 <= len(runs) <= 4 or workloads:
            raise SystemExit("pilot 08 takes one to four run reports (one per model)")
        return render_pilot_08([(p.as_posix(), r) for p, r in runs])
    raise SystemExit(f"unknown pilot {pilot!r} (04, 05, 06, 07 or 08)")


def render(doc: str) -> str:
    if doc in PILOT_04_05_DOCS:
        paths = [DATA / name for name in PILOTS[doc]]
        body = analyse(PILOT_04_05_DOCS[doc], paths)
        # the document already has its "## Results" heading
        if body and body[0].startswith("## Results"):
            body = body[1:]
        return "\n".join([START, *body, END])
    if doc == PILOT_03_DOC:
        lines3: list[str] = [
            START,
            "",
            "Format: k/n (rate, Wilson 95% interval). Scenario ids are shortened to their "
            "number (see Scenarios). Preset `vulnerable` only.",
            "",
        ]
        for name in PILOTS[doc]:
            lines3 += render_pilot_03(load(name), name)
        lines3.append(END)
        return "\n".join(lines3)
    if doc == PILOT_02_DOC:
        lines: list[str] = [
            START,
            "",
            "Format: k/n (rate, Wilson 95% interval). Scenario ids are shortened to their "
            "number (004 cross-customer read, 008 foreign history, 009 dispute flow, 010 payee "
            "name, 011 read before pay, 012 key swap). Preset `vulnerable` only.",
            "",
        ]
        for name in PILOTS[doc]:
            lines += render_pilot_02(load(name), name)
        lines.append(END)
        return "\n".join(lines)
    lines = [
        START,
        "",
        "Format: k/n (rate, Wilson 95% interval). Scenario ids are shortened to their "
        "number (001 injection, 002 confused deputy, 003 payee name, 004 cross-customer "
        "read, 005 structuring, 006 foreign debit, 007 drain). Preset `vulnerable` only.",
        "",
    ]
    for name in PILOTS[doc]:
        lines += render_model(load(name), name)
    lines.append(END)
    return "\n".join(lines)


def updated(doc: str) -> tuple[str, str]:
    text = (ROOT / doc).read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    return text, text[:start] + render(doc) + text[end:]


def main(argv: list[str]) -> int:
    if "--pilot" in argv:
        parser = argparse.ArgumentParser(prog="python -m scripts.pilot_results")
        parser.add_argument("--pilot", required=True, choices=("04", "05", "06", "07", "08"))
        parser.add_argument("--report", action="append", type=Path, required=True)
        args = parser.parse_args(argv)
        print("\n".join(analyse(args.pilot, args.report)))
        return 0
    stale = []
    for doc in PILOTS:
        old, new = updated(doc)
        if old != new:
            stale.append(doc)
            if "--check" not in argv:
                (ROOT / doc).write_text(new, encoding="utf-8", newline="\n")
    if "--check" in argv and stale:
        print("out of date: " + ", ".join(stale))
        return 1
    print("rewritten: " + (", ".join(stale) or "nothing"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
