"""Post-hoc attribution re-analysis of the committed pilot 01 and 02 reports.

Usage: uv run python scripts/reanalyze.py [--check]

Re-runs only the attribution layer (mulebench.harness.attribution) on the
stored outgoing transfers, INV-1 results and traces of the reports in
docs/experiments/data/, with the current builtin scenarios, and rewrites the
block between the markers of docs/experiments/reanalysis-01-02.md. The frozen
pilot documents and data are never written. With --check, nothing is written
and the exit code is 1 if the block is out of date (tests/test_reanalysis.py
runs the same check).
"""

from __future__ import annotations

import sys
from pathlib import Path

from mulebench.attacks import load_builtin
from mulebench.harness.attribution import attribute_stored
from mulebench.harness.models import Attribution, CellResult, Report
from mulebench.harness.stats import Rate, wilson
from mulebench.reports.reader import load_report

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "experiments" / "data"
DOC = ROOT / "docs" / "experiments" / "reanalysis-01-02.md"
START = "<!-- reanalysis:start (generated by scripts/reanalyze.py; do not edit) -->"
END = "<!-- reanalysis:end -->"

REPORTS = [
    ("Pilot 01, qwen3-14b-8k", "pilot-01-qwen3-14b-8k.json"),
    ("Pilot 01, llama31-8b-8k", "pilot-01-llama31-8b-8k.json"),
    ("Pilot 02, qwen3-14b-8k", "pilot-02-qwen3-14b-8k.json"),
]
PROMPT_SHORT = {"baseline": "baseline", "data_not_instructions": "data_not_instr."}


def rate(r: Rate | None) -> str:
    if r is None or r.n == 0 or r.rate is None or r.low is None or r.high is None:
        return "n/a (n=0)"
    return f"{r.k}/{r.n} ({r.rate:.0%}, {r.low:.0%}-{r.high:.0%})"


def short_id(scenario_id: str) -> str:
    return scenario_id.rsplit("-", 1)[-1]


def attributions(report: Report) -> dict[tuple[str, str, str, int], Attribution]:
    """(scenario, prompt, variant, trial) -> attribution, non-errored trials only."""
    scenarios = {s.id: s for s in load_builtin()}
    out: dict[tuple[str, str, str, int], Attribution] = {}
    for result in report.scenarios:
        s = scenarios[result.scenario_id]
        for cell in result.cells:
            for t in cell.trials:
                if t.errored:
                    continue
                key = (result.scenario_id, cell.prompt_variant, cell.variant, t.trial)
                out[key] = attribute_stored(s, cell.variant, t)
    return out


def _cell_rows(
    report: Report, attr: dict[tuple[str, str, str, int], Attribution]
) -> tuple[list[str], list[str], list[str]]:
    attack_rows: list[str] = []
    benign_rows: list[str] = []
    changed: list[str] = []
    for result in sorted(report.scenarios, key=lambda r: short_id(r.scenario_id)):
        sid = short_id(result.scenario_id)
        for cell in sorted(result.cells, key=lambda c: (c.variant, c.prompt_variant)):
            ok = [t for t in cell.trials if not t.errored]
            a = [attr[(result.scenario_id, cell.prompt_variant, cell.variant, t.trial)] for t in ok]
            prompt = PROMPT_SHORT.get(cell.prompt_variant, cell.prompt_variant)
            task_error = wilson(sum(x.task_error for x in a), len(a))
            omitted = wilson(sum(x.task_omitted for x in a), len(a))
            if cell.variant == "attack":
                attack_rows.append(_attack_row(sid, prompt, cell, a, task_error, omitted))
                for t, x in zip(ok, a, strict=True):
                    policy = t.status == "exposed_violated"
                    direction = bool(t.payload_exposed) and x.attack_success is True
                    if policy != direction:
                        changed.append(
                            f"| {sid} | {prompt} | {t.trial} | "
                            f"{'violated' if policy else t.status} | "
                            f"{'yes' if direction else 'no'} | {', '.join(x.reasons) or '-'} |"
                        )
            elif cell.benign is not None:
                benign_rows.append(
                    f"| {sid} | {prompt} | {rate(cell.benign.utility_exact)} | "
                    f"{rate(task_error)} | {rate(omitted)} |"
                )
    return attack_rows, benign_rows, changed


def _attack_row(
    sid: str,
    prompt: str,
    cell: CellResult,
    a: list[Attribution],
    task_error: Rate,
    omitted: Rate,
) -> str:
    if cell.attack is None:
        raise ValueError("attack cell without attack aggregates")
    ok = [t for t in cell.trials if not t.errored]
    exposed = [x for t, x in zip(ok, a, strict=True) if t.payload_exposed]
    attributed = wilson(sum(x.attack_success is True for x in exposed), len(exposed))
    return (
        f"| {sid} | {prompt} | {rate(cell.attack.attack_success)} | {rate(attributed)} | "
        f"{rate(task_error)} | {rate(omitted)} |"
    )


def render() -> str:
    lines: list[str] = []
    for title, name in REPORTS:
        report = load_report(DATA / name)
        attr = attributions(report)
        attack_rows, benign_rows, changed = _cell_rows(report, attr)
        lines += [
            f"### {title} (`{name}`)",
            "",
            "Attack cells. Policy success is the frozen `attack_success` (exposed and an "
            "expected invariant violated / exposed); attributed success uses the same "
            "denominator; task error and omission are over non-errored trials.",
            "",
            "| Scenario | Prompt | Policy success (frozen) | Attributed success "
            "| Task error | Task omitted |",
            "|---|---|---|---|---|---|",
            *attack_rows,
            "",
            "Benign controls. Utility is the frozen exact utility.",
            "",
            "| Scenario | Prompt | Utility (frozen) | Task error | Task omitted |",
            "|---|---|---|---|---|",
            *benign_rows,
            "",
        ]
        if changed:
            lines += [
                "Attack trials where policy success and attributed success differ:",
                "",
                "| Scenario | Prompt | Trial | Frozen status | Attributed success | Reasons |",
                "|---|---|---|---|---|---|",
                *changed,
                "",
            ]
        else:
            lines += ["No attack trial changes between policy and attributed success.", ""]
    return "\n".join(lines).rstrip() + "\n"


def updated() -> tuple[str, str]:
    old = DOC.read_text(encoding="utf-8")
    head, rest = old.split(START, 1)
    _, tail = rest.split(END, 1)
    return old, f"{head}{START}\n{render()}{END}{tail}"


def main(argv: list[str]) -> int:
    old, new = updated()
    if "--check" in argv:
        if old != new:
            print(f"{DOC.relative_to(ROOT).as_posix()} is stale: run scripts/reanalyze.py")
            return 1
        return 0
    if old != new:
        DOC.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {DOC.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
