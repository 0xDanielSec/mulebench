"""Page shell, slugs and small formatting helpers shared by the viewer pages."""

from __future__ import annotations

import hashlib
import re
from collections.abc import Sequence

from mulebench.harness.stats import Rate
from mulebench.viewer.assets import CSP, CSS, JS
from mulebench.viewer.html import Markup, frag, h

_SLUG = re.compile(r"[^a-z0-9]+")

# Badge kinds map to CSS classes; the text always names the outcome, so the
# color is never the only signal.
BadgeKind = str  # "bad" | "good" | "warn" | "info" | "neutral"


def slug(value: str) -> str:
    """File-name safe and stable; a hash suffix keeps distinct ids distinct."""
    s = _SLUG.sub("-", value.lower()).strip("-") or "x"
    if s != value:
        s += "-" + hashlib.sha256(value.encode("utf-8")).hexdigest()[:8]
    return s


def brl(cents: int) -> str:
    sign = "-" if cents < 0 else ""
    cents = abs(cents)
    return f"{sign}R$ {cents // 100:,}.{cents % 100:02d}"


def rate(r: Rate | None) -> str:
    if r is None:
        return "—"
    if r.n == 0 or r.rate is None or r.low is None or r.high is None:
        return f"{r.k}/{r.n}"
    return f"{r.k}/{r.n} ({r.rate:.0%}, {r.low:.0%}-{r.high:.0%})"


def badge(kind: BadgeKind, text: str) -> Markup:
    return h("span", {"class": f"badge {kind}"}, text)


def dl(items: Sequence[tuple[str, object]]) -> Markup:
    return h("dl", None, [frag(h("dt", None, k), h("dd", None, v)) for k, v in items])


def table(
    caption: str,
    headers: Sequence[str],
    rows: Sequence[Sequence[object]],
    *,
    table_id: str | None = None,
    numeric: Sequence[int] = (),
) -> Markup:
    head = h(
        "thead",
        None,
        h(
            "tr",
            None,
            [
                h("th", {"scope": "col", "class": "num" if i in numeric else None}, x)
                for i, x in enumerate(headers)
            ],
        ),
    )
    body = h(
        "tbody",
        None,
        [
            h(
                "tr",
                None,
                [
                    (
                        h("th", {"scope": "row"}, c)
                        if i == 0
                        else h("td", {"class": "num" if i in numeric else None}, c)
                    )
                    for i, c in enumerate(row)
                ],
            )
            for row in rows
        ],
    )
    return h(
        "div",
        {"class": "scroll"},
        h("table", {"id": table_id}, h("caption", None, caption), head, body),
    )


def page(
    title: str,
    crumbs: Sequence[tuple[str, str | None]],
    *content: object,
) -> str:
    """A complete document. `crumbs` are (label, relative href or None for current)."""
    nav = h(
        "nav",
        {"aria-label": "Breadcrumb"},
        h(
            "ol",
            None,
            [
                h(
                    "li",
                    None,
                    h("a", {"href": href}, label)
                    if href is not None
                    else h("span", {"aria-current": "page"}, label),
                )
                for label, href in crumbs
            ],
        ),
    )
    toggle = h(
        "button",
        {"id": "theme-toggle", "type": "button", "aria-pressed": "false", "hidden": True},
        "Toggle dark mode",
    )
    doc = h(
        "html",
        {"lang": "en"},
        h(
            "head",
            None,
            h("meta", {"charset": "utf-8"}),
            h("meta", {"http-equiv": "Content-Security-Policy", "content": CSP}),
            h("meta", {"name": "viewport", "content": "width=device-width, initial-scale=1"}),
            h("meta", {"name": "referrer", "content": "no-referrer"}),
            h("title", None, f"{title} · mulebench"),
            h("style", None, Markup(CSS)),
        ),
        h(
            "body",
            None,
            h("a", {"class": "skip", "href": "#main"}, "Skip to content"),
            h("header", None, nav, toggle),
            h("main", {"id": "main", "tabindex": "-1"}, h("h1", None, title), *content),
            h(
                "footer",
                None,
                h(
                    "p",
                    {"class": "muted"},
                    "Generated by mulebench view. Synthetic data only. "
                    "Model reasoning is never stored or shown.",
                ),
            ),
            h("script", None, Markup(JS)),
        ),
    )
    return "<!DOCTYPE html>\n" + doc + "\n"
